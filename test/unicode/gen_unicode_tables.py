#!/usr/bin/env python3
"""Generate lib/unicode_data.warp (the tables of lib/unicode.warp) and the sampled NormalizationTest pairs files.

Rerun: download UnicodeData.txt, CompositionExclusions.txt, CaseFolding.txt and NormalizationTest.txt of the pinned
version from https://www.unicode.org/Public/15.1.0/ucd/ into a directory, then
    python3 test/unicode/gen_unicode_tables.py <that directory>
from the repository root. The raw UCD files are not committed."""
import sys, os
VERSION = "15.1.0"
ucd = sys.argv[1] if len(sys.argv) > 1 else "/tmp/ucd"
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
def lines(name):
    for l in open(os.path.join(ucd, name), encoding="utf-8"):
        l = l.split("#")[0].strip()
        if l: yield l
first = open(os.path.join(ucd, "NormalizationTest.txt"), encoding="utf-8").readline()
assert VERSION in first, first
ccc = {}; decomp = {}
for l in lines("UnicodeData.txt"):
    f = l.split(";"); cp = int(f[0], 16)
    if f[1].endswith("First>") or f[1].endswith("Last>"): continue  # ranges (Hangul, CJK) have no ccc or mapping
    if int(f[3]): ccc[cp] = int(f[3])
    if f[5]:
        d = f[5].split(); compat = d[0].startswith("<")
        if compat: d = d[1:]
        decomp[cp] = (compat, [int(x, 16) for x in d])
# ccc as runs: gap from the previous run's end, length, class
runs = []; prev = None
for cp in sorted(ccc):
    if runs and cp == runs[-1][0] + runs[-1][1] and ccc[cp] == runs[-1][2]: runs[-1][1] += 1
    else: runs.append([cp, 1, ccc[cp]])
out = []; end = 0
for s, n, c in runs: out.append("%d %d %d" % (s - end, n, c)); end = s + n
ccc_text = " ".join(out)
# decompositions: gap from the previous key, 0 canonical or 1 compatibility, then the code points; a run of
# consecutive keys each to one code point at the same distance is "gap flag *count delta"
out = []; last = 0; keys = sorted(decomp); i = 0
while i < len(keys):
    cp = keys[i]; compat, d = decomp[cp]; j = i + 1
    if len(d) == 1:
        while j < len(keys) and keys[j] == cp + (j - i) and decomp[keys[j]][0] == compat and len(decomp[keys[j]][1]) == 1 and decomp[keys[j]][1][0] - keys[j] == d[0] - cp: j += 1
    if j - i >= 3:
        out.append("%d %d *%d %d" % (cp - last, 1 if compat else 0, j - i, d[0] - cp)); last = keys[j - 1]; i = j
    else:
        out.append("%d %d %s" % (cp - last, 1 if compat else 0, " ".join(str(x) for x in d))); last = cp; i += 1
decomp_text = ";".join(out)
excl = sorted(int(l.split()[0], 16) for l in lines("CompositionExclusions.txt"))
excl_text = " ".join(str(x) for x in excl)
# case folding C+F: one-to-one ones as runs (start gap, count, stride, delta), many-to-one listed
single = {}; multi = {}
for l in lines("CaseFolding.txt"):
    f = [x.strip() for x in l.split(";")]
    if f[1] not in ("C", "F"): continue
    cp = int(f[0], 16); t = [int(x, 16) for x in f[2].split()]
    if len(t) == 1: single[cp] = t[0]
    else: multi[cp] = t
fold = []
for cp in sorted(single):
    d = single[cp] - cp
    if fold:
        s, n, stride, delta = fold[-1]
        if delta == d and (n == 1 and cp - s <= 2 or n > 1 and cp == s + n * stride):
            if n == 1: fold[-1][2] = cp - s
            fold[-1][1] += 1; continue
    fold.append([cp, 1, 1, d])
out = []; end = 0
for s, n, stride, d in fold: out.append("%d %d %d %d" % (s - end, n, stride, d)); end = s + (n - 1) * stride
fold_text = " ".join(out)
multi_text = ";".join("%d %s" % (cp, " ".join(str(x) for x in t)) for cp, t in sorted(multi.items()))
warp = '''# Generated by test/unicode/gen_unicode_tables.py (Unicode %s), do not edit: the tables of lib/unicode.warp,
# texts of decimal numbers it reads on first use. ccc: runs (gap from the last run's end, length, class).
# decompositions: entries (gap from the last code point, 1 when compatibility, its code points) split by ;.
# exclusions: CompositionExclusions.txt. folding: runs (gap from the last run's last code point, count, stride,
# delta) of CaseFolding.txt's one-to-one C+F mappings, then its F mappings to several code points (code point, those)
unicode_version = "%s"
unicode_ccc_text(): text := "%s"
unicode_decomposition_text(): text := "%s"
unicode_exclusion_text(): text := "%s"
unicode_folding_text(): text := "%s"
unicode_folding_multi_text(): text := "%s"
''' % (VERSION, VERSION, ccc_text, decomp_text, excl_text, fold_text, multi_text)
open(os.path.join(root, "lib", "unicode_data.warp"), "w", encoding="utf-8").write(warp)
print("lib/unicode_data.warp", len(warp.encode()), "bytes;", len(runs), "ccc runs,", len(decomp), "decompositions,", len(fold), "fold runs,", len(multi), "multi")

# --- the sampled tests: NormalizationTest.txt Part 0 whole, every 100th line of Part 1 (with every 1000th Hangul
# syllable line and every composition exclusion line), every 15th of Part 2, every 4th of Part 3; eight lines a case
lit = lambda s: "'" + s.replace("\\", "\\\\").replace("'", "\\'") + "'"
parts = {}; part = None
for l in open(os.path.join(ucd, "NormalizationTest.txt"), encoding="utf-8"):
    if l.startswith("@Part"): part = l.split()[0][1:]; continue
    body = l.split("#")[0].strip()
    if not body: continue
    parts.setdefault(part, []).append([[int(x, 16) for x in c.split()] for c in body.split(";")[:5]])
excluded = set(excl)
picked = [("Part0, all of it", parts["Part0"]),
          ("Part1, every 100th line", parts["Part1"][::100]),
          ("Part1, Hangul syllables (every 1000th)", [r for r in parts["Part1"] if 0xAC00 <= r[0][0] <= 0xD7A3][::1000]),
          ("Part1, the composition exclusions", [r for r in parts["Part1"] if len(r[0]) == 1 and r[0][0] in excluded]),
          ("Part2, canonical order of several marks, every 15th line", parts["Part2"][::15]),
          ("Part3, PRI #29, every 4th line", parts["Part3"][::4])]
L = ["// lib/unicode.warp nfc, nfd, nfkc, nfkd: a sample of NormalizationTest-%s.txt; every case checks the invariants of all five" % VERSION,
     "// columns of eight lines under all four forms ([] for a line that holds). Generated by test/unicode/gen_unicode_tables.py"]
total = 0
for title, rows in picked:
    L.append("// " + title + " (%d lines)" % len(rows)); total += len(rows)
    for i in range(0, len(rows), 8):
        group = rows[i:i + 8]
        L.append(lit("use unicode; [normalization_check(r) for r in %s]" % str(group).replace(" ", "")) + "\t" + "[" + ", ".join("[]" for _ in group) + "]")
open(os.path.join(root, "test", "modules", "test_unicode_normalization.pairs.warp"), "w", encoding="utf-8").write("\n".join(L) + "\n")
print("test_unicode_normalization:", sum(1 for l in L if l.startswith("'")), "cases,", total, "lines")

# --- casefold, is_normalized and the text forms, their expected values from python3's unicodedata and str.casefold
import unicodedata
assert unicodedata.unidata_version == VERSION, "cross-checks need python's unicodedata at " + VERSION
W = lambda t: '"' + t.replace("\\", "\\\\").replace('"', '\\"') + '"'
N = lambda t: "text_of_codepoints(%s)" % str([ord(c) for c in t]).replace(" ", "")
L = ["// lib/unicode.warp casefold (CaseFolding.txt C+F, no Turkic T), is_normalized and unicode_normalize on texts; expected values",
     "// from python3 %s (str.casefold, unicodedata). Generated by test/unicode/gen_unicode_tables.py" % VERSION]
def case(code, exp): L.append(lit("use unicode; " + code) + "\t" + exp)
L.append("// full folding: one code point to several (status F), and the simple ones (status C)")
for t in ["Straße", "MASSE", "ẞ", "ﬃ", "ΣΑΣ ς", "Ǆ ǅ", "ŉ", "ΐ", "Ꭰ", "ᏸ", "𐐀", "ＡＢＣ", "KELVIN K", "Hello, World!"]:
    case("codepoint_numbers(casefold(%s))" % N(t), str([ord(c) for c in t.casefold()]))
L.append("// İ folds to i and U+0307 (status F), I to i: the Turkic mappings (status T, İ to i, I to ı) are not applied")
case("codepoint_numbers(casefold(%s))" % N("İ"), "[105, 775]")
case("casefold(\"I\")", W("i"))
case("casefold(\"Straße\") == casefold(\"STRASSE\")", "true")
L.append("// is_normalized in every form")
for t in ["e\u0301", "\u00e9", "\ufb01", "\u1e0b\u0323", "\u1e0d\u0307", "\u212b", "한", "\u1112\u1161\u11ab", "abc"]:
    for f in ["NFC", "NFD", "NFKC", "NFKD"]:
        case("is_normalized(%s, %s)" % (N(t), W(f)), "true" if unicodedata.is_normalized(f, t) else "false")
L.append("// unicode_normalize on texts, and its forms in any case")
for t in ["Å", "ﬁ", "①", "ｶﾞ", "한국어", "q\u0307\u0323", "\u0958", "x\u0301\u0300\u0327"]:
    for f in ["nfc", "NFD", "Nfkc", "NFKD"]:
        case("codepoint_numbers(unicode_normalize(%s, %s))" % (N(t), W(f)), str([ord(c) for c in unicodedata.normalize(f.upper(), t)]))
case("codepoint_numbers(nfc(text_of_codepoints([101,769]))) == codepoint_numbers(nfc(nfd(text_of_codepoints([233]))))", "true")
case("try { unicode_normalize(\"x\", \"NFX\") } catch e { e.message }", W("unicode_normalize: the form is NFC, NFD, NFKC or NFKD, not NFX"))
case("combining_class(769)", "230")
case("combining_class(65)", "0")
open(os.path.join(root, "test", "modules", "test_unicode_casefold.pairs.warp"), "w", encoding="utf-8").write("\n".join(L) + "\n")
print("test_unicode_casefold:", sum(1 for l in L if l.startswith("'")), "cases")
