#!/usr/bin/env python3
# Writes lib/html_entities.warp, HTML_ENTITY_CODES: every named character reference of WHATWG's entities.json
# (test/html/entities.json), keyed by its name without the & (with its ; or, for the legacy ones, without).
# usage: test/html/gen_html_entities.py   (from the repository root)
import json, os
root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
data = json.load(open(os.path.join(root, "test/html/entities.json"), encoding="utf-8"))
def W(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == "\\": out.append("\\\\")
        elif ch == '"': out.append('\\"')
        elif ch == "\n": out.append("\\n")
        elif ch == "\t": out.append("\\t")
        elif o < 32 or o == 127 or 0x80 <= o < 0xA0 or 0x300 <= o < 0x370 or 0x20D0 <= o < 0x2100 or o in (0x200B, 0x200C, 0x200D, 0x2060, 0xFE00, 0xFE01, 0x2061, 0x2062, 0x2063, 0x205F, 0x200A, 0x2009, 0x2008, 0x2007, 0x2005, 0x2004, 0x2003, 0x2002, 0x00A0):
            out.append('" + chr(%d) + "' % o)
        else: out.append(ch)
    return ('"' + "".join(out) + '"').replace(' + ""', "").replace('"" + ', "")
items = sorted(data.items())
# one ASCII text searched by name: " name=hex" for each, the code points in hex (two joined by ,), a space after the
# last (a map literal of 2231 entries makes every program that uses html compile seconds longer, and building the map
# at run time costs seconds too)
body = "".join(" %s=%s" % (name[1:], ",".join("%X" % p for p in v["codepoints"])) for name, v in items) + " "
lines = ["// Generated by test/html/gen_html_entities.py from WHATWG's entities.json (test/html/entities.json): do not edit.",
         "// HTML_ENTITY_CODES: every named character reference, \" name=hex\" each, the name without the & (\"amp;\", and",
         f"// \"amp\" for the legacy names that may end without a ;), its code points in hex: {len(items)} names; lib/html reads it.",
         'HTML_ENTITY_CODES = "' + body + '"']
open(os.path.join(root, "lib/html_entities.warp"), "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(len(items), "names")
