// Warp Int is a mathematical integer: i64 fast path, BigInt on overflow (wasm_emitter/big_int.rs)
use warp::extensions::numbers::Number;
use warp::wasm_emitter::eval;
use warp::{is, Node};

fn int(digits: &str) -> Node {
	Node::Number(Number::parse_integer(digits).unwrap())
}

#[test]
fn test_big_literal_round_trip() {
	is!("123456789012345678901234567890", int("123456789012345678901234567890"));
	is!("-123456789012345678901234567890", int("-123456789012345678901234567890"));
	is!("9223372036854775807", i64::MAX); // i64::MAX lies beyond the fixnum range
	is!("-9223372036854775808", i64::MIN);
}

#[test]
fn test_overflow_promotes_add_sub() {
	is!("9223372036854775807 + 1", int("9223372036854775808"));
	is!("4611686018427387904 + 4611686018427387904", int("9223372036854775808"));
	is!("-9223372036854775808 - 1", int("-9223372036854775809"));
	is!("x=4611686018427387904; x+x+x", int("13835058055282163712"));
	is!("123456789012345678901234567890 - 123456789012345678901234567889", 1); // demotes on the way back
}

#[test]
fn test_overflow_promotes_mul() {
	is!("square(x) := x*x; square(3037000500)", int("9223372037000250000"));
	is!("4294967296 * 4294967296", int("18446744073709551616"));
	is!("-4294967296 * 4294967296 * 4294967296", int("-79228162514264337593543950336"));
	is!("123456789012345678901234567890 * 987654321098765432109876543210", int("121932631137021795226185032733622923332237463801111263526900"));
	is!("3037000500²", int("9223372037000250000"));
}

#[test]
fn test_overflow_promotes_pow() {
	is!("2^64", int("18446744073709551616"));
	is!("2^100", int("1267650600228229401496703205376"));
	is!("(-3)^41", int("-36472996377170786403"));
	is!("10^30 / 10^30", 1.0);
}

#[test]
fn test_overflow_promotes_neg_abs() {
	is!("x=-9223372036854775808; -x", int("9223372036854775808"));
	is!("x=-9223372036854775808; abs(x)", int("9223372036854775808"));
	is!("x=4611686018427387904; -x", -4611686018427387904i64);
}

#[test]
fn test_big_division_and_remainder() {
	is!("123456789012345678901234567890 % 1000000007", 197434842);
	is!("-123456789012345678901234567890 % 1000", -890);
	is!("123456789012345678901234567890 % 98765432109876543210", int("60185185207253086410"));
	is!("x=123456789012345678901234567890; x /= 1000000000000; x", int("123456789012345678"));
}

#[test]
fn test_comparisons_across_small_and_big() {
	is!("2^64 > 2^63", true);
	is!("2^70 > 5", true);
	is!("-(2^70) < 5", true);
	is!("2^70 == 2^70", true);
	is!("2^70 != 2^70 + 1", true);
	is!("2^62 == 4611686018427387904", true);
	is!("x=2^80; y=2^79*2; x==y", true);
	is!("-(2^70) < -(2^69)", true);
}

#[test]
fn test_factorial_and_fib_stay_exact() {
	is!("fac(n) := n<2 ? 1 : n*fac(n-1); fac(25)", int("15511210043330985984000000"));
	is!("x=1; i=0; while i<100 { x = x*2; i++ }; x", int("1267650600228229401496703205376"));
}

#[test]
fn test_big_int_to_float() {
	is!("2^70 + 0.5", 1180591620717411303424.0);
}

#[test]
fn test_i64_opt_out_wraps() {
	is!("(3037000500*3037000500) as i64", -9223372036709301616i64);
	is!("(9223372036854775807 + 1) as i64", i64::MIN);
	is!("(2^64) as i64", 0);
	is!("x=3037000500; (x*x) as i64", -9223372036709301616i64);
	is!("(3037000500*3037000500) as int", int("9223372037000250000")); // int stays exact
}

#[test]
fn test_small_arithmetic_unchanged() {
	is!("3+3", 6);
	is!("7*6-2", 40);
	is!("-7 % 3", -1);
	is!("x=5; x*=3; x", 15);
	let result = eval("i=0; s=0; while i<1000 { s+=i; i++ }; s");
	assert_eq!(result, 499500);
}
