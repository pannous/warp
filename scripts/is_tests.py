#!/usr/bin/env python3
"""The Rust tests' is!("code", expected) assertions as warp files (decision warp-is-tests, notes/is_tests.md).

    scripts/is_tests.py [tests/<topic>/test_x.rs …]   default: every tests/**/test_*.rs
    scripts/is_tests.py run [normal|emitter|pure …] [-- tests/<topic>/test_x.warp …]
                                                    the fast lane: `warp test` of each file (default all) in each lane
                                                    (default all three), passed / failed / refused counted per lane;
                                                    logs in data/is_tests/, warp binary $WARP or scratch/warp

Writes beside each Rust file holding a translatable is! two files, under a `# fn name` line per Rust test:
tests/<topic>/test_x.pairs.warp, pure data, one `'code'⇥expected` pair a line (tab separated, a list of lists to warp's
reader) for the short tests (one line of code, a literal expectation, at most PAIR_WIDTH characters), and tests/<topic>/test_x.warp
with an `is! 'code' expected` line for each other one. Prints the counts of written and skipped assertions, skips by
reason.
The code must be a string literal, a const of the file or a format! of those; the expected value a literal, a list of
ints, ø or a parse of plain data. Anything else is skipped and counted, never guessed. Tests marked #[ignore] are
skipped too: they fail in Rust already.
"""
import os
import re
import subprocess
import sys
from collections import Counter
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
TESTS = REPO / "tests"
PAIRS_SUFFIX = ".pairs.warp"
PAIR_WIDTH = 80  # the line limit: a longer test stays an is! line (decision warp-is-tests)
HEADER = "# generated by scripts/is_tests.py from {name}: edit the Rust test, then run the script again\n"
IS_CALL = re.compile(r"(?<![\w!])is!\(")
TEST_FN = re.compile(r"\bfn\s+(\w+)\s*\(")
CONST = re.compile(r"\b(?:const\s+(\w+)\s*:\s*&(?:'static\s+)?str|let\s+(\w+)(?:\s*:\s*&str)?)\s*=\s*")
IGNORE_ATTRIBUTE = re.compile(r"#\[ignore\b")
RUST_SUFFIX = r"(?:_?(?:i8|i16|i32|i64|i128|isize|u8|u16|u32|u64|u128|usize|f32|f64))?"
UNSIGNED = r"(0x[\da-fA-F_]+|0b[01_]+|\d[\d_]*(\.[\d_]*)?(e-?\d+)?)" + RUST_SUFFIX
NUMBER = re.compile("-?" + UNSIGNED)
PI_WORDS = {"PI", "std::f64::consts::PI", "f64::consts::PI", "π"}
# `+ - *` and comparisons mean the same in warp; `/` of two ints is a ratio there, an int in Rust
ARITHMETIC_TOKEN = re.compile(r"\s*(" + UNSIGNED + r"|[\w:]+|<=|>=|==|!=|[-+*<>()])")
EMPTY_VALUES = {"Empty", "Node::Empty", "warp::Node::Empty", "warp::node::Node::Empty", "ø"}
# the lanes of the fast lane: the switches each sets (src/compiler/self_hosted.rs)
LANES = {"normal": {}, "emitter": {"WARP_SELF_HOSTED": "1"}, "pure": {"WARP_SELF_HOSTED": "pure"}}
QUIET = {"WARP_NO_WINDOW": "1", "WARP_HINTS": "0"}
REFUSALS = "WARP_EMIT_REFUSALS"
REFUSED = "outside the core: "  # how a refusal line starts (self_hosted.rs OUTSIDE_THE_CORE)
REFUSAL_SHOWN = 60  # characters of a refusal that rank it
RUN_DATA = REPO / "data" / "is_tests"
JOBS = 4  # warp test processes at once: the Mac is shared (notes/roles.md)
FILE_SECONDS = 300  # a file still running then counts as timed out
# at a line's end: a program's print without a newline runs into it (`123✓ 2 tests passed`)
SUMMARY = re.compile(r"(?:✓ (\d+) tests? passed|(\d+) of (\d+) failed)$", re.M)
BOOLS = {"true": "true", "false": "false", "True": "true", "False": "false"}
INT_LISTS = re.compile(r"(?:warp::)?(?:ints|texts|strings|floats)\(\s*(?:&\s*)?vec!\[(.*)\]\s*\)", re.S)
LIST_LITERAL = re.compile(r"(?:vec!|&)?\[(.*)\]", re.S)
INT_CALL = re.compile(r"(?:warp::)?(?:int|Node::int)\((.*)\)", re.S)
PARSE_CALL = re.compile(r"(?:warp::)?parse\((.*)\)", re.S)
TEXT_CALL = re.compile(r"(?:warp::)?(?:text|Node::text)\((.*)\)", re.S)
PLAIN_DATA = re.compile(r"[\d\s\[\](){},.:;\-+]*")


def rust_string_at(source, at):
    """The string literal starting at source[at] ("…", r"…", r#"…"#) as (value, end), else None"""
    raw = re.match(r'r(#*)"', source[at:])
    if raw:
        hashes = raw.group(1)
        start = at + raw.end()
        end = source.find('"' + hashes, start)
        return (source[start:end], end + 1 + len(hashes)) if end >= 0 else None
    if source[at] != '"':
        return None
    value, i = [], at + 1
    while i < len(source):
        c = source[i]
        if c == '"':
            return "".join(value), i + 1
        if c != "\\":
            value.append(c)
            i += 1
            continue
        escaped = source[i + 1]
        if escaped == "\n":  # a line continuation skips the next line's indentation
            i += 2
            while i < len(source) and source[i] in " \t\n\r":
                i += 1
            continue
        if escaped == "u":
            close = source.index("}", i)
            value.append(chr(int(source[i + 3 : close], 16)))
            i = close + 1
            continue
        if escaped == "x":
            value.append(chr(int(source[i + 2 : i + 4], 16)))
            i += 4
            continue
        value.append({"n": "\n", "t": "\t", "r": "\r", "0": "\0"}.get(escaped, escaped))
        i += 2
    return None


def skip_comment_or_string(source, at):
    """The end of the comment, string or char literal at source[at], else None"""
    if source.startswith("//", at):
        end = source.find("\n", at)
        return len(source) if end < 0 else end
    if source.startswith("/*", at):
        end = source.find("*/", at)
        return len(source) if end < 0 else end + 2
    if source[at] == '"' or (source[at] == "r" and re.match(r'r#*"', source[at:]) and not source[at - 1 : at].isalnum()):
        string = rust_string_at(source, at)
        return string[1] if string else len(source)
    char = re.match(r"'(\\.[^']*|[^'\\])'", source[at:])
    if char:
        return at + char.end()
    return None


def call_arguments(source, at):
    """The top-level comma-separated arguments of the call whose `(` is at source[at], and the end after `)`"""
    depth, start, i, arguments = 0, at + 1, at, []
    while i < len(source):
        end = skip_comment_or_string(source, i)
        if end is not None:
            i = end
            continue
        c = source[i]
        if c in "([{":
            depth += 1
        elif c in ")]}":
            depth -= 1
            if depth == 0:
                arguments.append(source[start:i].strip())
                return [a for a in arguments if a], i + 1
        elif c == "," and depth == 1:
            arguments.append(source[start:i].strip())
            start = i + 1
        i += 1
    return arguments, len(source)


def file_consts(source):
    """The file's string consts and `let` strings, those of one value only (a name bound twice is no constant)"""
    values = {}
    for match in CONST.finditer(source):
        string = rust_string_at(source, match.end())
        name = match.group(1) or match.group(2)
        if string and source[string[1] :].lstrip().startswith(";"):
            values.setdefault(name, set()).add(string[0])
        else:
            values.setdefault(name, set()).add(None)
    return {name: value.pop() for name, value in values.items() if len(value) == 1 and None not in value}


def whole_string(expression):
    string = rust_string_at(expression, 0) if expression else None
    return string[0] if string and string[1] == len(expression) else None


def code_of(expression, consts):
    """The warp code an is! argument holds, or None"""
    expression = expression.strip()
    while expression.startswith("&"):
        expression = expression[1:].strip()
    expression = re.sub(r"\.(to_string|as_str|to_owned)\(\)$", "", expression)
    if (string := whole_string(expression)) is not None:
        return string
    if expression in consts:
        return consts[expression]
    format_call = re.fullmatch(r"format!\((.*)\)", expression, re.S)
    if not format_call:
        return None
    arguments, _ = call_arguments("(" + format_call.group(1) + ")", 0)
    template = whole_string(arguments[0]) if arguments else None
    if template is None:
        return None
    named = {k.strip(): v for k, v in (a.split("=", 1) for a in arguments[1:] if "=" in a and "==" not in a)}
    positional = [a for a in arguments[1:] if not ("=" in a and "==" not in a)]
    missing = []

    def hole(match):
        name = match.group(1)
        if name == "":
            if not positional:
                missing.append(name)
                return ""
            value = code_of(positional.pop(0), consts)
        elif name in named:
            value = code_of(named[name], consts)
        else:
            value = consts.get(name)
        if value is None:
            missing.append(name)
            return ""
        return value

    filled = re.sub(r"\{(\w*)\}", hole, template.replace("{{", "\x01").replace("}}", "\x02"))
    return None if missing else filled.replace("\x01", "{").replace("\x02", "}")


def warp_number(written):
    number = re.sub(RUST_SUFFIX + "$", "", written.replace("_", ""))
    if re.fullmatch(r"-?0[xb][\da-fA-F]+", number):
        return str(int(number, 0))
    if number.endswith("."):
        number += "0"
    float_suffix = re.search(r"f(32|64)$", written) and "." not in number and "e" not in number
    return number + ".0" if float_suffix else number


def warp_text(text):
    """A warp text literal holding `text` as it is: in single quotes, where nothing interpolates"""
    plain = "\\" not in text and "\r" not in text and "\0" not in text
    if plain and "'" not in text and "»" not in text and "«" not in text:
        return "'" + text + "'"
    if plain and "»" not in text:
        return "«" + text + "»"
    escaped = text.replace("\\", "\\\\").replace("'", "\\'").replace("\r", "\\r").replace("\0", "\\u{0}")
    return "'" + escaped + "'"


def expected_of(expression, consts):
    """The warp value an is! expectation writes, or (None, why)"""
    expression = expression.strip()
    expression = re.sub(r"^\((.*)\)$", r"\1", expression, flags=re.S).strip()
    if NUMBER.fullmatch(expression):
        return warp_number(expression), None
    if expression in BOOLS:
        return BOOLS[expression], None
    if expression.startswith("!") and expression[1:] in BOOLS:
        return {"true": "false", "false": "true"}[BOOLS[expression[1:]]], None
    if expression in EMPTY_VALUES:
        return "ø", None
    if (string := whole_string(expression.lstrip("&"))) is not None:
        return warp_text(string), None
    char = re.fullmatch(r"'(\\.[^']*|[^'\\])'", expression)
    if char:
        value = rust_string_at('"' + char.group(1) + '"', 0)[0]
        return warp_text(value), None
    if (arithmetic := warp_arithmetic(expression)) is not None:
        return arithmetic, None
    for pattern in (INT_LISTS, LIST_LITERAL):
        listed = pattern.fullmatch(expression)
        if listed:
            items, _ = call_arguments("(" + listed.group(1) + ")", 0)
            values = [expected_of(item, consts) for item in items]
            if all(value is not None for value, _ in values):
                return "[" + ", ".join(value for value, _ in values) + "]", None
            return None, "list item"
    for pattern in (INT_CALL, TEXT_CALL):
        called = pattern.fullmatch(expression)
        if called:
            inner = called.group(1).strip()
            string = whole_string(inner)
            if pattern is INT_CALL and string is not None and NUMBER.fullmatch(string.strip()):
                return warp_number(string.strip()), None
            return expected_of(inner, consts)
    parsed = PARSE_CALL.fullmatch(expression)
    if parsed:
        data = code_of(parsed.group(1), consts)
        if data is not None and PLAIN_DATA.fullmatch(data):
            return data.strip(), None
        return None, "parse of non-plain data"
    head = re.match(r"[\w:]+", expression)
    return None, "expected " + (head.group(0) if head else expression[:12])


def warp_arithmetic(expression):
    """`1 + PI`, `3 < 1`, `10 + 3000 * 3001`: numbers, pi and `+ - * < >` as warp writes them, else None"""
    tokens, at = [], 0
    while at < len(expression):
        token = ARITHMETIC_TOKEN.match(expression, at)
        if not token:
            return None
        word = token.group(1)
        if NUMBER.fullmatch(word):
            tokens.append(warp_number(word))
        elif word in PI_WORDS:
            tokens.append("pi")
        elif re.fullmatch(r"<=|>=|==|!=|[-+*<>()]", word):
            tokens.append(word)
        else:
            return None
        at = token.end()
    operators = [t for t in tokens if not re.fullmatch(r"[\d.]+|[()]", t)]
    return " ".join(tokens).replace("( ", "(").replace(" )", ")") if operators else None


def computed(value):
    """`1 + pi`, `3 < 1`: an expectation warp computes, no literal"""
    return value[0] not in "['«" and re.search(r"\s[-+*<>=!]", value) is not None


def argument(value):
    """`-1` and `1 + pi` in parentheses: after a word's argument they would subtract and add"""
    return f"({value})" if value.startswith("-") or computed(value) else value


def pair_line(code, expected):
    """The pairs file's `'code'⇥expected` line; None for a test that stays an is!"""
    if "\n" in code or "\t" in code or computed(expected):
        return None
    line = warp_text(code) + "\t" + expected
    return line if len(line.expandtabs()) <= PAIR_WIDTH else None


def pairs_path(rust_test):
    return rust_test.with_name(rust_test.stem + PAIRS_SUFFIX)


def ignored_spans(source):
    """The (start, end) of each #[ignore] test function body"""
    spans = []
    for attribute in IGNORE_ATTRIBUTE.finditer(source):
        function = TEST_FN.search(source, attribute.end())
        if not function:
            continue
        body = source.find("{", function.end())
        _, end = call_arguments(source.replace("{", "(").replace("}", ")"), body) if body >= 0 else (None, body)
        spans.append((function.start(), end))
    return spans


def code_spans(source):
    """Where comments are: is! inside them is no assertion"""
    spans, i = [], 0
    while i < len(source):
        end = skip_comment_or_string(source, i)
        if end is None:
            i += 1
            continue
        if source.startswith("//", i) or source.startswith("/*", i):
            spans.append((i, end))
        i = end
    return spans


def inside(spans, at):
    return any(start <= at < end for start, end in spans)


def translate(path, counts, reasons):
    source = path.read_text()
    consts = file_consts(source)
    ignored, comments = ignored_spans(source), code_spans(source)
    files = {pairs_path(path): [], path.with_suffix(".warp"): []}
    last_function = {}
    for call in IS_CALL.finditer(source):
        if inside(comments, call.start()):
            continue
        counts["seen"] += 1
        if inside(ignored, call.start()):
            reasons["#[ignore] test"] += 1
            continue
        if source[max(0, call.start() - 6) : call.start()].endswith("skip!("):
            reasons["skip!"] += 1
            continue
        arguments, _ = call_arguments(source, call.end() - 1)
        if len(arguments) != 2:
            reasons["gc / other arity"] += 1
            continue
        code = code_of(arguments[0], consts)
        if code is None:
            reasons["code not a literal"] += 1
            continue
        expected, why = expected_of(arguments[1], consts)
        if expected is None:
            reasons[why] += 1
            continue
        functions = list(TEST_FN.finditer(source, 0, call.start()))
        function = functions[-1].group(1) if functions else None
        pair = pair_line(code, expected)
        target = pairs_path(path) if pair else path.with_suffix(".warp")
        if function != last_function.get(target):
            files[target].append(f"\n# {function}")
            last_function[target] = function
        files[target].append(pair or f"is! {warp_text(code)} {argument(expected)}")
        counts["written"] += 1
    header = HEADER.format(name=path.name)
    generated = {target: not target.exists() or target.read_text().startswith(header) for target in files}
    if not all(generated.values()):
        reasons["beside a hand-written .warp"] += sum(line[:1] not in "\n" for lines in files.values() for line in lines)
        return
    for target, lines in files.items():
        if lines:
            target.write_text(header + "\n".join(lines) + "\n")
            counts["files"] += 1
        elif target.exists():
            target.unlink()


def tested(file, lane, warp):
    """`warp test file` in the lane: (passed, failed, unrun, output); a file without its summary (a crash, a timeout,
    a lane that missed the is! lines) leaves each of its is! lines unrun"""
    environment = {**os.environ, **QUIET, **LANES[lane], REFUSALS: str(RUN_DATA / f"{lane}.refusals")}
    try:
        run = subprocess.run([warp, "test", str(file)], capture_output=True, text=True, timeout=FILE_SECONDS, env=environment)
        output = run.stdout + run.stderr
    except subprocess.TimeoutExpired:
        output = f"timed out after {FILE_SECONDS} s"
    summary = ([None] + list(SUMMARY.finditer(output)))[-1]
    if not summary:
        tests = sum(bool(line.strip()) and not line.startswith(("#", "//")) for line in file.read_text().splitlines())
        return 0, 0, tests, output
    if summary.group(1):
        return int(summary.group(1)), 0, 0, output
    failed, run_count = int(summary.group(2)), int(summary.group(3))
    return run_count - failed, failed, 0, output


def run_lanes(arguments):
    lanes = [a for a in arguments if a in LANES] or list(LANES)
    files = [Path(f).resolve() for f in arguments[arguments.index("--") + 1 :]] if "--" in arguments else []
    beside = (target for path in TESTS.rglob("test_*.rs") for target in (path.with_suffix(".warp"), pairs_path(path)))
    files = files or sorted(target for target in beside if target.exists())
    warp = os.environ.get("WARP", str(REPO / "scratch" / "warp"))
    RUN_DATA.mkdir(parents=True, exist_ok=True)
    for lane in lanes:
        (RUN_DATA / f"{lane}.refusals").write_text("")
        with ThreadPoolExecutor(JOBS) as pool:
            results = list(pool.map(lambda file: tested(file, lane, warp), files))
        with open(RUN_DATA / f"{lane}.log", "w") as log:
            for file, (*_, output) in zip(files, results):
                log.write(f"== {file.relative_to(REPO)}\n{output}\n")
        passed, failed, unrun = (sum(result[at] for result in results) for at in range(3))
        unrun_files = sum(result[2] > 0 for result in results)
        lines = (RUN_DATA / f"{lane}.refusals").read_text().splitlines()
        refusals = Counter(line.removeprefix(REFUSED)[:REFUSAL_SHOWN] for line in lines)
        refused = f"{len(lines)}, most: " + "; ".join(f"{count}× {why}" for why, count in refusals.most_common(5))
        total = passed + failed + unrun
        print(f"{lane}: {passed} passed, {failed} failed, {unrun} unrun (no summary from {unrun_files} files) of {total}"
              f" in {len(files)} files; refusals: {refused}")


def main():
    if sys.argv[1:2] == ["run"]:
        return run_lanes(sys.argv[2:])
    files = [Path(f).resolve() for f in sys.argv[1:]] or sorted(TESTS.rglob("test_*.rs"))
    counts, reasons = Counter(), Counter()
    for path in files:
        translate(path, counts, reasons)
    skipped = counts["seen"] - counts["written"]
    print(f"{counts['written']} of {counts['seen']} is! written into {counts['files']} files, {skipped} skipped:")
    for reason, count in reasons.most_common():
        print(f"  {count:6}  {reason}")


if __name__ == "__main__":
    main()
