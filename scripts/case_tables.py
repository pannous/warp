#!/usr/bin/env python3
"""Writes lib/case_tables.warp: the case tables of lib/case_table.warp (card case-table-warp), Python's Unicode case
mappings as flat int lists of six fields per range: start, last, stride, delta, second, third. Writes
lib/letter_ranges.warp too: the code points of Unicode's letters (categories L*) beyond ASCII, two fields per range
(start, last), which lib/text.warp's is_unicode_letter searches. The Unicode version is Python's
(`python3 -c "import unicodedata; print(unicodedata.unidata_version)"`)."""
import pathlib
import sys
import unicodedata

OUTPUT = pathlib.Path(__file__).resolve().parent.parent / "lib" / "case_tables.warp"
LETTERS_OUTPUT = OUTPUT.with_name("letter_ranges.warp")
FIRST_BEYOND_ASCII = 0x80
STRIDES = (1, 2)
LAST_CODE_POINT = 0x10FFFF
SURROGATES = range(0xD800, 0xE000)
INTS_WORD = "ints_of"


def accent_free(letter):
	"""The letter's first code point when its canonical decomposition adds only combining marks (`í` → `i`)"""
	parts = unicodedata.normalize("NFD", letter)
	accented = len(parts) > 1 and all(unicodedata.category(part).startswith("M") for part in parts[1:])
	return parts[0] if accented else letter


MAPPINGS = {
	"upper": lambda letter: letter.upper(),
	"lower": lambda letter: letter.lower(),
	"fold": lambda letter: accent_free(letter).lower(),
}


def extends(range_, code, delta):
	start, last, stride, range_delta, second, _ = range_
	step = code - last
	stride_fits = step in STRIDES if last == start else step == stride
	return range_delta == delta and second == 0 and stride_fits


def case_ranges(mapping):
	ranges = []
	for code in range(LAST_CODE_POINT + 1):
		if code in SURROGATES:
			continue
		mapped = [ord(part) for part in mapping(chr(code))]
		if mapped == [code]:
			continue
		delta = mapped[0] - code
		if ranges and len(mapped) == 1 and extends(ranges[-1], code, delta):
			ranges[-1][2] = code - ranges[-1][1]
			ranges[-1][1] = code
			continue
		more = lambda slot: mapped[slot] if slot < len(mapped) else 0
		ranges.append([code, code, 1, delta, more(1), more(2)])
	return ranges


# the ints as one text read when the module loads: a 9,600-int list literal took wasmtime 39 s to compile (debug);
# the text as a word of its own, which core/runtime.warp reads too (`use case_tables`)
def warp_list(name, ranges):
	numbers = " ".join(str(field) for range_ in ranges for field in range_)
	return f'{name}_case_text(): text := "{numbers}"\n{name}_case_ranges = {INTS_WORD}({name}_case_text())\n'


def letter_ranges():
	"""[start, last] of each run of letters beyond ASCII"""
	ranges = []
	for code in range(FIRST_BEYOND_ASCII, LAST_CODE_POINT + 1):
		if code in SURROGATES or not unicodedata.category(chr(code)).startswith("L"):
			continue
		if ranges and ranges[-1][1] == code - 1:
			ranges[-1][1] = code
		else:
			ranges.append([code, code])
	return ranges


def write_letters():
	numbers = " ".join(str(field) for range_ in letter_ranges() for field in range_)
	LETTERS_OUTPUT.write_text(
		"# Generated by scripts/case_tables.py (Unicode " + unicodedata.unidata_version + "), do not edit: the letters\n"
		"# beyond ASCII (Unicode's categories L*) as ranges of two ints, start and last, sorted by start\n"
		f'letter_text(): text := "{numbers}"\n'
		'letter_ranges = [digits as int for digits in letter_text().split(" ")]\n')
	print(f"wrote {LETTERS_OUTPUT}", file=sys.stderr)


def main():
	header = (
		"# Generated by scripts/case_tables.py (Unicode " + unicodedata.unidata_version + "), do not edit: the case ranges of\n"
		"# lib/case_table.warp, six ints each (start, last, stride, delta, second, third), sorted by start\n"
		"\n# the ints of a text of them, a space apart\n"
		f"{INTS_WORD}(t: text): list := [digits as int for digits in t.split(\" \")]\n\n"
	)
	tables = [warp_list(name, case_ranges(mapping)) for name, mapping in MAPPINGS.items()]
	OUTPUT.write_text(header + "\n".join(tables))
	print(f"wrote {OUTPUT}", file=sys.stderr)
	write_letters()


if __name__ == "__main__":
	main()
